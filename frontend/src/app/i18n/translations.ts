/**
 * BCP-47 locale used to format dates/times per UI language. Swiss locales for the
 * national languages (de/fr/it), regional defaults otherwise. Kept in one place so
 * date formatting stays in sync with the set of UI languages.
 */
const LOCALES: Record<Language, string> = {
  de: 'de-CH',
  en: 'en-GB',
  fr: 'fr-CH',
  it: 'it-CH',
  es: 'es-ES',
};

export function localeFor(language: Language): string {
  return LOCALES[language];
}

